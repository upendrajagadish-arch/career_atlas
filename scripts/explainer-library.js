/* Teaching notes for the in-app lectures.
   Each entry is original explanation text used when a topic names that idea.
   Longer phrases are matched first. Edit the generated JSON in assets/explainers/
   if you only want to change one lecture. */
function teach(phrase, what, why, steps, example, details, mistakes, prereqs) {
  return {
    phrase,
    what,
    why,
    steps: steps || [],
    example: example || [],
    details: details || [],
    mistakes: mistakes || [],
    prereqs: prereqs || [],
  };
}

